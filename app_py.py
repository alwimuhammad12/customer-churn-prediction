# -----------------------------------------------------------------------------
# 2. LOAD ARTEFAK MODEL PIPELINE
# -----------------------------------------------------------------------------
@st.cache_resource
def load_pipeline():
    return joblib.load('churn_prediction_pipeline.joblib')

try:
    artifacts = load_pipeline()
    model = artifacts['model']
    threshold = artifacts['best_threshold']
    selected_features = artifacts['selected_features']
    feedback_map = artifacts['feedback_map']
except Exception as e:
    st.error(f"Gagal memuat file pipeline `churn_prediction_pipeline.joblib`: {e}")
    st.stop()

# -----------------------------------------------------------------------------
# 3. HELPER PREPROCESSING DATA
# -----------------------------------------------------------------------------
def preprocess_input(df_raw):
    df_proc = df_raw.copy()

    # Feature Engineering
    df_proc['points_per_membership_day'] = df_proc['points_in_wallet'] / (df_proc['membership_days'] + 1)
    df_proc['avg_transaction_per_login'] = df_proc['avg_transaction_value'] / (df_proc['avg_frequency_login_days'] + 1)
    df_proc['feedback_sentiment'] = df_proc['feedback'].map(feedback_map).fillna('Neutral')

    # One-Hot Encoding
    df_encoded = pd.get_dummies(df_proc, columns=[
        'region_category', 'membership_category', 'joined_through_referral',
        'preferred_offer_types', 'offer_application_preference', 'feedback_sentiment', 'gender'
    ])

    # Menyesuaikan kolom dengan urutan data latih
    features_to_predict = [col for col in selected_features if col != 'churn_risk_score']
    for col in features_to_predict:
        if col not in df_encoded.columns:
            df_encoded[col] = 0

    return df_encoded[features_to_predict]

