# TAB 2: BATCH PREDICTION (CSV UPLOAD)
# -----------------------------------------------------------------------------
with tab2:
    st.subheader("📂 Evaluasi Churn Massal (Batch Processing)")
    uploaded_file = st.file_uploader("Unggah file CSV data pelanggan", type=["csv"])

    if uploaded_file is not None:
        batch_df = pd.read_csv(uploaded_file)
        st.write("Preview Data Masukan:", batch_df.head(3))

        try:
            X_batch = preprocess_input(batch_df)
            batch_probs = model.predict_proba(X_batch)[:, 1]
            batch_preds = (batch_probs >= threshold).astype(int)

            batch_df['Churn_Probability'] = np.round(batch_probs, 4)
            batch_df['Predicted_Churn'] = np.where(batch_preds == 1, 'Churn Risk', 'Retained')

            col_b1, col_b2, col_b3 = st.columns(3)
            total_cust = len(batch_df)
            churn_count = (batch_preds == 1).sum()
            churn_pct = (churn_count / total_cust) * 100

            col_b1.metric("Total Pelanggan", f"{total_cust:,}")
            col_b2.metric("Prediksi Churn", f"{churn_count:,}", delta=f"{churn_pct:.1f}%", delta_color="inverse")
            col_b3.metric("Prediksi Retained", f"{total_cust - churn_count:,}")

            # Donut Chart Distribusi
            fig_pie = px.pie(
                batch_df,
                names='Predicted_Churn',
                title='Distribusi Prediksi Populasi',
                color='Predicted_Churn',
                color_discrete_map={'Churn Risk': '#EF4444', 'Retained': '#10B981'},
                hole=0.4
            )
            fig_pie.update_layout(paper_bgcolor="rgba(0,0,0,0)", plot_bgcolor="rgba(0,0,0,0)")
            st.plotly_chart(fig_pie, use_container_width=True)

            # Download Button Hasil Prediksi
            csv_result = batch_df.to_csv(index=False).encode('utf-8')
            st.download_button(
                label="📥 Unduh Hasil Prediksi (CSV)",
                data=csv_result,
                file_name="churn_predictions_result.csv",
                mime="text/csv"
            )
        except Exception as err:
            st.error(f"Gagal memproses file batch: {err}")

