preferred_offer_types = st.sidebar.selectbox("Preferred Offer", ['Gift Vouchers/Coupons', 'Credit/Debit Card Offers', 'Without Offers'])
joined_through_referral = st.sidebar.radio("Joined Referral?", ['Yes', 'No'], horizontal=True)

